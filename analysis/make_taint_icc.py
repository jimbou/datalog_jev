"""Generate analysis/taint_icc.dl: taint.dl plus inter-component (Intent) holes (experiment 4).

A send site is a call that hands an Intent to the framework (startActivity..., startService, bindService, sendBroadcast...).
For every component C of the matching kind in the app's manifest, the pair (send site, C) is a candidate hole whose source is
the sent Intent and whose targets are the Intents C receives: the result of getIntent() in C (or a superclass of C that
declares the calling method) and the Intent parameter of C's onReceive / onStartCommand / onBind / onNewIntent /
onHandleIntent / onStart. The candidates use the same relations as library holes (CandSrc, CandTgtV), so taint,
relevance and the stored graph need no change; they appear in RelCand with class "#icc" and the pair as signature.

Answer key, computed here and written to IccLabel: "yes" if some object the Intent may point to (only those created in the sending method, when there are any) names C explicitly
(Intent(ctx, C.class), setClass, setClassName, setComponent(new ComponentName(ctx, C.class))) or carries a constant action
that C's manifest filter lists; "unk" if some such object has neither an explicit target nor a constant action (or the
Intent variable points to nothing); otherwise "no". Receivers registered at run time (registerReceiver) are not modeled.
Inputs added: Component.facts (class, kind, exported) and IntentFilter.facts (class, action) from extract/Manifest.java.
Usage: make_taint_icc.py     (writes analysis/taint_icc.dl)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SENDS = [  # (callee sub-signature, component kind); the Intent is argument 0 in all of them
    ("void startActivity(android.content.Intent)", "activity"),
    ("void startActivity(android.content.Intent,android.os.Bundle)", "activity"),
    ("void startActivityForResult(android.content.Intent,int)", "activity"),
    ("void startActivityForResult(android.content.Intent,int,android.os.Bundle)", "activity"),
    ("void startActivities(android.content.Intent[])", "activity"),
    ("android.content.ComponentName startService(android.content.Intent)", "service"),
    ("android.content.ComponentName startForegroundService(android.content.Intent)", "service"),
    ("boolean bindService(android.content.Intent,android.content.ServiceConnection,int)", "service"),
    ("void sendBroadcast(android.content.Intent)", "receiver"),
    ("void sendBroadcast(android.content.Intent,java.lang.String)", "receiver"),
    ("void sendOrderedBroadcast(android.content.Intent,java.lang.String)", "receiver"),
    ("void sendStickyBroadcast(android.content.Intent)", "receiver"),
]
RECV_PARAMS = [  # (sub-signature declared by the component, index of the Intent parameter)
    ("void onReceive(android.content.Context,android.content.Intent)", 1),
    ("int onStartCommand(android.content.Intent,int,int)", 0),
    ("void onStart(android.content.Intent,int)", 0),
    ("android.os.IBinder onBind(android.content.Intent)", 0),
    ("void onNewIntent(android.content.Intent)", 0),
    ("void onHandleIntent(android.content.Intent)", 0),
    ("void onRebind(android.content.Intent)", 0),
]

BLOCK = r'''
// ==== inter-component holes (generated by make_taint_icc.py) ====
.decl Component(c:symbol, kind:symbol, exported:symbol)
.decl IntentFilter(c:symbol, action:symbol)
.input Component, IntentFilter
.decl IccSend(sub:symbol, kind:symbol)
%(sends)s
.decl IccRecvParam(sub:symbol, i:number)
%(params)s
.decl CompOrSuper(comp:symbol, cls:symbol)
CompOrSuper(c, c) :- Component(c, _, _).
CompOrSuper(c, s) :- Component(c, _, _), SubType(c, s).
.decl RecvVar(comp:symbol, v:Var)
RecvVar(c, r) :- Call(_, m, _, _, "android.content.Intent getIntent()", _, r), r != "-", MethodDecl(cls, _, m, _, _), CompOrSuper(c, cls).
RecvVar(c, v) :- IccRecvParam(sub, i), MethodDecl(cls, sub, m, _, _), CompOrSuper(c, cls), FormalParam(m, i, v).
.decl IccCand(isite:symbol, sv:Var, comp:symbol)
IccCand(cat(site, " -> ", c), sv, c) :- LibCall(site, _, sub, _, _), IccSend(sub, kind), Arg(site, 0, sv),
    !match("str:.*", sv), !match("cls:.*", sv), sv != "-", Component(c, kind, _), RecvVar(c, _).
.decl IccSite(isite:symbol, site:symbol)
IccSite(cat(site, " -> ", c), site) :- LibCall(site, _, sub, _, _), IccSend(sub, kind), Component(c, kind, _), RecvVar(c, _).
CandSrc(isite, 0, sv) :- IccCand(isite, sv, _).
CandTgtV(isite, 0, v) :- IccCand(isite, _, c), RecvVar(c, v).
RelCand(cat("c:", isite, "#0"), cat("v:", sv), "#icc", isite, 0) :- BM(isite, 0), IccCand(isite, sv, _), BV(sv).

// answer key for the candidates that ended up relevant
.decl ClsArg(site:symbol, i:number, c:symbol)
ClsArg(site, i, substr(a, 4, strlen(a) - 4)) :- Arg(site, i, a), (match("cls:.*", a) ; match("str:.*", a)).
.decl CnTarget(h:symbol, c:symbol)
CnTarget(h, c) :- Call(site, _, _, "android.content.ComponentName", sub, b, _), Pts(b, h), ClsArg(site, 1, c),
    (sub = "void <init>(android.content.Context,java.lang.Class)" ; sub = "void <init>(java.lang.String,java.lang.String)" ;
     sub = "void <init>(android.content.Context,java.lang.String)").
.decl IntentTarget(h:symbol, c:symbol)
IntentTarget(h, c) :- Call(site, _, _, "android.content.Intent", sub, b, _), Pts(b, h), ClsArg(site, 1, c),
    (sub = "void <init>(android.content.Context,java.lang.Class)" ;
     sub = "android.content.Intent setClass(android.content.Context,java.lang.Class)" ;
     sub = "android.content.Intent setClassName(android.content.Context,java.lang.String)" ;
     sub = "android.content.Intent setClassName(java.lang.String,java.lang.String)").
IntentTarget(h, c) :- Call(site, _, _, "android.content.Intent", "void <init>(java.lang.String,android.net.Uri,android.content.Context,java.lang.Class)", b, _),
    Pts(b, h), ClsArg(site, 3, c).
IntentTarget(h, c) :- Call(site, _, _, "android.content.Intent", "android.content.Intent setComponent(android.content.ComponentName)", b, _),
    Pts(b, h), Arg(site, 0, cn), Pts(cn, h2), CnTarget(h2, c).
.decl IntentAction(h:symbol, a:symbol)
IntentAction(h, substr(a, 4, strlen(a) - 4)) :- Call(site, _, _, "android.content.Intent", sub, b, _), Pts(b, h), Arg(site, 0, a), match("str:.*", a),
    (sub = "void <init>(java.lang.String)" ; sub = "void <init>(java.lang.String,android.net.Uri)" ;
     sub = "android.content.Intent setAction(java.lang.String)").
// the key reads the Intent objects created in the sending method itself when there are any (context-insensitive points-to
// merges Intents built by shared helpers); otherwise every object the sent variable may point to
.decl LocalHeap(isite:symbol, h:symbol)
LocalHeap(i, h) :- IccCand(i, sv, _), IccSite(i, site), Call(site, m, _, _, _, _, _), Pts(sv, h), contains(m, h).
.decl HasLocal(isite:symbol)
HasLocal(i) :- LocalHeap(i, _).
.decl KeyHeap(isite:symbol, h:symbol)
KeyHeap(i, h) :- LocalHeap(i, h).
KeyHeap(i, h) :- IccCand(i, sv, _), !HasLocal(i), Pts(sv, h).
.decl HasTgt(h:symbol)
HasTgt(h) :- IntentTarget(h, _).
.decl HasAct(h:symbol)
HasAct(h) :- IntentAction(h, _).
.decl HasPts(v:Var)
HasPts(v) :- Pts(v, _).
.decl IccYes(isite:symbol)
IccYes(i) :- IccCand(i, _, c), KeyHeap(i, h), IntentTarget(h, c).
IccYes(i) :- IccCand(i, _, c), KeyHeap(i, h), !HasTgt(h), IntentAction(h, a), IntentFilter(c, a).
.decl IccUnk(isite:symbol)
IccUnk(i) :- KeyHeap(i, h), !HasTgt(h), !HasAct(h).
IccUnk(i) :- IccCand(i, sv, _), !HasPts(sv).
.decl IccLabel(isite:symbol, label:symbol)
IccLabel(i, "yes") :- BM(i, 0), IccCand(i, _, _), IccYes(i).
IccLabel(i, "unk") :- BM(i, 0), IccCand(i, _, _), !IccYes(i), IccUnk(i).
IccLabel(i, "no") :- BM(i, 0), IccCand(i, _, _), !IccYes(i), !IccUnk(i).
.output IccLabel(compress=true)
// what a pricer may read about a relevant candidate: the Intent's constant targets and actions, the component's kind and filter
.decl IccInfo(isite:symbol, what:symbol, value:symbol)
IccInfo(i, "target", c2) :- BM(i, 0), KeyHeap(i, h), IntentTarget(h, c2).
IccInfo(i, "action", a) :- BM(i, 0), KeyHeap(i, h), IntentAction(h, a).
IccInfo(i, "kind", k) :- BM(i, 0), IccCand(i, _, c), Component(c, k, _).
IccInfo(i, "exported", e) :- BM(i, 0), IccCand(i, _, c), Component(c, _, e).
IccInfo(i, "filter", a) :- BM(i, 0), IccCand(i, _, c), IntentFilter(c, a).
.output IccInfo(compress=true)
Stats("icc_cands", n) :- n = count : { IccCand(_, _, _) }.
Stats("icc_rel", n) :- n = count : { IccLabel(_, _) }.
'''


def main():
    base = open(os.path.join(ROOT, "analysis/taint.dl")).read()
    sends = "\n".join('IccSend("%s", "%s").' % s for s in SENDS)
    params = "\n".join('IccRecvParam("%s", %d).' % p for p in RECV_PARAMS)
    out = "// GENERATED by analysis/make_taint_icc.py from taint.dl; do not edit\n" + base + BLOCK % {"sends": sends, "params": params}
    open(os.path.join(ROOT, "analysis/taint_icc.dl"), "w").write(out)
    print("wrote analysis/taint_icc.dl")


if __name__ == "__main__":
    main()
