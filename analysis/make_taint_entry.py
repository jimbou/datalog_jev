"""Generate analysis/taint_entry.dl from analysis/taint.dl: the same analysis restricted to code reachable from entry points.

taint.dl treats every method shipped in the APK as live. Here a method is live only if it is an entry point or can be called
from one (CHA call graph, edges as in taint.dl). Calls in dead methods are dropped before everything else, so sources, sinks and
library calls in dead code disappear. Entry points approximate what FlowDroid builds its dummy main from:
  - instance methods of app classes whose supertype chain reaches an android.* type or Runnable, Thread, TimerTask, Callable
    (components, lifecycle methods and registered callbacks, since a callback class implements a framework interface),
  - lambda bodies (reached through invokedynamic, which the call graph does not resolve),
  - static class initializers.
Usage: make_taint_entry.py     (rewrites analysis/taint_entry.dl)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ENTRY = '''
// ---- entry points and reachability (only in the entry-restricted variant) ----
.decl CallAll(site:symbol, m:symbol, kind:symbol, cls:symbol, sub:symbol, base:symbol, ret:symbol)
.input CallAll(IO=file, filename="Call.facts")
.decl FwType(s:symbol)
FwType(s) :- Super(_, s), !Class(s, _), match("android\\\\..*", s).
FwType("java.lang.Runnable").
FwType("java.lang.Thread").
FwType("java.util.TimerTask").
FwType("java.util.concurrent.Callable").
.decl FwBased(c:symbol)
FwBased(c) :- Super(c, s), FwType(s).
FwBased(c) :- Super(c, s), FwBased(s).
.decl Entry(m:symbol)
Entry(m) :- MethodDecl(c, _, m, "instance", "concrete"), FwBased(c).
Entry(m) :- MethodDecl(_, sub, m, _, "concrete"), match(".*lambda\\\\$.*", sub).
Entry(m) :- MethodDecl(_, "void <clinit>()", m, _, "concrete").
.decl TargetAll(site:symbol, m:symbol)
TargetAll(site, m) :- CallAll(site, _, kind, c, sub, _, _), (kind = "static" ; kind = "special"), Resolve(c, sub, m).
TargetAll(site, m) :- CallAll(site, _, "virtual", c, sub, _, _), Class(c, _), SubType(d, c), Class(d, "class"), Resolve(d, sub, m).
.decl Reach(m:symbol)
Reach(m) :- Entry(m).
Reach(m2) :- Reach(m1), CallAll(site, m1, _, _, _, _, _), TargetAll(site, m2).
Call(site, m, kind, cls, sub, base, ret) :- CallAll(site, m, kind, cls, sub, base, ret), Reach(m).
'''


def main():
    s = open(os.path.join(ROOT, "analysis/taint.dl")).read()
    s = s.replace(".input Alloc, Move, Load, Store, SLoad, SStore, Call, Arg,", ".input Alloc, Move, Load, Store, SLoad, SStore, Arg,")
    assert ", Call," not in s.split(".input", 1)[1].split("\n", 1)[0], "the Call input must be replaced"
    s = s.replace("// ---- call graph (CHA restricted to types shipped in the APK) ----", ENTRY + "\n// ---- call graph (CHA restricted to types shipped in the APK) ----", 1)
    s = s.replace('.output Stats\n', 'Stats("methods", n) :- n = count : { MethodDecl(_, _, _, _, "concrete") }.\nStats("reach_methods", n) :- n = count : { Reach(_) }.\n.output Stats\n')
    s = "// GENERATED by analysis/make_taint_entry.py from taint.dl: the same analysis restricted to code reachable from entry points.\n" + s
    assert "CallAll" in s and "Reach(m)" in s
    open(os.path.join(ROOT, "analysis/taint_entry.dl"), "w").write(s)
    print("wrote analysis/taint_entry.dl")


if __name__ == "__main__":
    main()
