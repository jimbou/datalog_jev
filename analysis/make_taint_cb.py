"""Generate analysis/taint_cb.dl: taint.dl plus callback holes for objects exposed to JavaScript (F4a).

A registration site is a call that hands an app object to the framework, which later calls the object's methods: today
WebView.addJavascriptInterface(obj, name) (on WebView or an app subclass). For every concrete instance method m that the
classes obj may point to declare or inherit, the pair (site, m) is a candidate hole whose source is m's return value and
whose target is obj at the site: the framework (JavaScript in the page) may read what m returns. The candidates use the
same relations as library holes (CandSrc, CandTgtV), so taint, relevance and the stored graph need no change; they appear
in RelCand with class "#cb" and the pair as signature. TaintBench lists addJavascriptInterface as a sink, so a secret
returned by an exposed method reaches that sink through a "#cb" fact.

Answer key, written to CbLabel: "yes" if m is annotated @JavascriptInterface, or is public and the app targets an SDK below
17 (WebView then exposes every public method); "unk" if m is public, not annotated and the target SDK is unknown;
otherwise "no". Inputs added: MethodPublic.facts and MethodAnnot.facts (extract/Facts.java), TargetSdk.facts
(extract/Manifest.java).
Usage: make_taint_cb.py     (writes analysis/taint_cb.dl)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

REGISTER = [  # (framework class, sub-signature, index of the registered object)
    ("android.webkit.WebView", "void addJavascriptInterface(java.lang.Object,java.lang.String)", 0),
]
JS_ANNOT = "Landroid/webkit/JavascriptInterface;"

BLOCK = r'''
// ==== callback holes (generated by make_taint_cb.py) ====
.decl MethodPublic(m:symbol)
.decl MethodAnnot(m:symbol, a:symbol)
.decl TargetSdk(n:number)
.input MethodPublic, MethodAnnot, TargetSdk
.decl CbRegister(cls:symbol, sub:symbol, i:number)
%(register)s
.decl CbObj(site:symbol, o:Var)
CbObj(site, o) :- LibCall(site, c, sub, _, _), CbRegister(w, sub, i), SubT(c, w), Arg(site, i, o),
    !match("str:.*", o), !match("cls:.*", o), o != "-".
.decl CbMeth(site:symbol, o:Var, m:symbol)
CbMeth(site, o, m) :- CbObj(site, o), Pts(o, h), HeapType(h, t), Class(t, "class"), Resolve(t, sub, m),
    MethodDecl(_, sub, m, "instance", "concrete"), !contains("<init>", sub).
.decl CbCand(isite:symbol, r:Var, o:Var, m:symbol)
CbCand(cat(site, " -> ", m), r, o, m) :- CbMeth(site, o, m), RetVar(m, r).
CandSrc(isite, 0, r) :- CbCand(isite, r, _, _).
CandTgtV(isite, 0, o) :- CbCand(isite, _, o, _).
RelCand(cat("c:", isite, "#0"), cat("v:", r), "#cb", isite, 0) :- BM(isite, 0), CbCand(isite, r, _, _), BV(r).
// a returned object whose fields or elements hold taint (String[] ret; ret[0] = getDeviceId()) is read whole by the page
TM(isite, 0) :- CbCand(isite, r, _, _), Pts(r, h), TF(h, _).
BF(h, f) :- BM(isite, 0), CbCand(isite, r, _, _), Pts(r, h), TF(h, f).
RelCand(cat("c:", isite, "#0"), cat("f:", h, "|", f), "#cb", isite, 0) :- BM(isite, 0), CbCand(isite, r, _, _), Pts(r, h), BF(h, f).

// answer key for the candidates that ended up relevant
.decl HasSdk()
HasSdk() :- TargetSdk(_).
.decl CbYes(isite:symbol)
CbYes(i) :- CbCand(i, _, _, m), MethodAnnot(m, "%(annot)s").
CbYes(i) :- CbCand(i, _, _, m), MethodPublic(m), TargetSdk(n), n < 17.
.decl CbUnk(isite:symbol)
CbUnk(i) :- CbCand(i, _, _, m), MethodPublic(m), !HasSdk().
.decl CbLabel(isite:symbol, label:symbol)
CbLabel(i, "yes") :- BM(i, 0), CbCand(i, _, _, _), CbYes(i).
CbLabel(i, "unk") :- BM(i, 0), CbCand(i, _, _, _), !CbYes(i), CbUnk(i).
CbLabel(i, "no") :- BM(i, 0), CbCand(i, _, _, _), !CbYes(i), !CbUnk(i).
.output CbLabel(compress=true)
// what a pricer may read about a relevant candidate: the method, its annotations, whether it is public, the target SDK
.decl CbInfo(isite:symbol, what:symbol, value:symbol)
CbInfo(i, "method", m) :- BM(i, 0), CbCand(i, _, _, m).
CbInfo(i, "annotation", a) :- BM(i, 0), CbCand(i, _, _, m), MethodAnnot(m, a).
CbInfo(i, "public", "true") :- BM(i, 0), CbCand(i, _, _, m), MethodPublic(m).
CbInfo(i, "target_sdk", to_string(n)) :- BM(i, 0), CbCand(i, _, _, _), TargetSdk(n).
.output CbInfo(compress=true)
Stats("cb_cands", n) :- n = count : { CbCand(_, _, _, _) }.
Stats("cb_rel", n) :- n = count : { CbLabel(_, _) }.
'''


def main():
    base = open(os.path.join(ROOT, "analysis/taint.dl")).read()
    register = "\n".join('CbRegister("%s", "%s", %d).' % r for r in REGISTER)
    out = "// GENERATED by analysis/make_taint_cb.py from taint.dl; do not edit\n" + base + BLOCK % {"register": register, "annot": JS_ANNOT}
    open(os.path.join(ROOT, "analysis/taint_cb.dl"), "w").write(out)
    print("wrote analysis/taint_cb.dl")


if __name__ == "__main__":
    main()
